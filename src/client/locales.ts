/** Theme rules are display-word substitutions and must never rewrite a `{placeholder}` token. */
const PLACEHOLDER_TOKEN = /(\{\w+\})/u

function applyThemeRules(text: string, rules: ReadonlyArray<readonly [string, string]>): string {
  return text.split(PLACEHOLDER_TOKEN).map(part => {
    if (PLACEHOLDER_TOKEN.test(part)) return part
    let themed = part
    for (const [from, to] of rules) {
      if (themed.includes(from)) themed = themed.split(from).join(to)
    }
    return themed
  }).join('')
}

function themeLocale<T extends Record<string, string>>(source: T, language: 'zh' | 'en'): T {
  const rules = language === 'zh' ? THEME_ZH : THEME_EN
  const themed: Record<string, string> = {}
  for (const [key, value] of Object.entries(source)) themed[key] = applyThemeRules(value, rules)
  return themed as T
}

